-- Fix function search path security warning
-- All functions should have their search_path explicitly set for security

-- Update existing functions to set secure search_path
CREATE OR REPLACE FUNCTION public.update_services_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  NEW.updated_at = now();
  NEW.updated_by = auth.uid();
  RETURN NEW;
END;
$function$;

